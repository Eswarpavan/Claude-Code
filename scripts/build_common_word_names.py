"""Regenerate backend/catalystedge/data/common_word_names.txt.

Lists the one-word company names from SEC's company list that are also
ordinary English words ("Where", "Stock", "On", "Trump", "Monster"). The
ticker linker never links a company from one of these words alone; it needs
the ticker, a cashtag, the full multi-word name, or a provider tag.

Dev-only: needs `pip install wordfreq` and an SEC User-Agent. The app itself
only reads the generated text file. Word frequencies come from wordfreq
(data CC BY-SA 4.0, https://github.com/rspeer/wordfreq).

    SEC_USER_AGENT="Your Name you@example.com" python3 scripts/build_common_word_names.py
"""

from __future__ import annotations

import json
import os
import sys
import urllib.request
from pathlib import Path

from wordfreq import zipf_frequency

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from catalystedge.pipeline.ticker_link import FAMOUS_ONE_WORD_NAMES, make_aliases  # noqa: E402

OUT = ROOT / "backend/catalystedge/data/common_word_names.txt"
# Zipf 4.0 = roughly once per 100,000 words of ordinary English text.
ZIPF_THRESHOLD = 4.0
# Less frequent in general English, but common in market headlines, or names of
# indexes, funds and products (Gemini, Opus, Muse) rather than the listed company.
FINANCE_WORDS = {
    "atmos", "benchmark", "catalyst", "crypto", "cyber", "dow", "drilling", "fidelity", "flex", "frontier",
    "gemini", "genesis", "lithium", "macro", "metals", "minerals", "muse", "nasdaq", "opus", "packaging", "spark",
    "surge", "telecom", "token", "uptrend", "uranium", "vanguard",
}


def main() -> None:
    ua = os.environ.get("SEC_USER_AGENT")
    if not ua:
        sys.exit("set SEC_USER_AGENT (your name and email; SEC requires it)")
    req = urllib.request.Request("https://www.sec.gov/files/company_tickers.json", headers={"User-Agent": ua})
    data = json.load(urllib.request.urlopen(req, timeout=30))
    words = set()
    for row in data.values():
        for alias in make_aliases(str(row["ticker"]), row["title"], block_common_words=False):
            w = alias.lower()
            if " " in w or w in FAMOUS_ONE_WORD_NAMES:
                continue
            if zipf_frequency(w, "en") >= ZIPF_THRESHOLD or w in FINANCE_WORDS:
                words.add(w)
    OUT.write_text("# Generated by scripts/build_common_word_names.py. One lowercase word per line.\n"
                   + "\n".join(sorted(words)) + "\n")
    print(f"wrote {len(words)} words to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
